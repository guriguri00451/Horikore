function picker(lines: readonly string[]): () => string {
  let last = -1;
  return () => {
    if (lines.length === 1) return lines[0]!;
    let i = Math.floor(Math.random() * lines.length);
    if (i === last) i = (i + 1) % lines.length;
    last = i;
    return lines[i]!;
  };
}

const pickAwake = picker(AWAKE_MUTTER);
const pickCalled = picker(CALLED);
const pickAngry = picker(ANGRY);
const pickNodding = picker(NODDING);
const pickWake = picker(WAKE);
const pickWorkout = picker(WORKOUT);
const pickBeauty = picker(BEAUTY);
const pickWorkoutBusy = picker(WORKOUT_BUSY);
const pickBeautyBusy = picker(BEAUTY_BUSY);
const pickHit = picker(HIT);

export function lineForEnter(state: CharacterState, fromSleep = false): string | null {
  switch (state) {
    case "called":
      return pickCalled();
    case "angry":
      return pickAngry();
    case "awake":
      return fromSleep ? pickWake() : pickAwake();
    case "nodding":
      return pickNodding();
    case "workout":
      return pickWorkout();
    case "beauty":
      return pickBeauty();
    case "hit":
      return pickHit();
    case "sleeping":
      return null;
  }
}

export function busyReply(state: CharacterState): string {
  if (state === "workout") return pickWorkoutBusy();
  if (state === "beauty") return pickBeautyBusy();
  return "ん？";
}
